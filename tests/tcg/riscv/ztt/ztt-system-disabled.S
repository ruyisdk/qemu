#include "include/ztt-csr.h"

    .option norvc

    .macro EXPECT_ILLEGAL insn:vararg
    li      s0, 1
    lla     s1, .Lresume\@
    \insn
    j       fail
.Lresume\@:
    li      t0, 2
    bne     s0, t0, fail
    .endm

    .text
    .global _start
_start:
    lla     t0, trap_handler
    csrw    mtvec, t0
    EXPECT_ILLEGAL .word ZTT_AME_ACQUIRE(ZTT_R_A0, ZTT_R_A1)
    EXPECT_ILLEGAL csrr t0, CSR_AMENLEN
    EXPECT_ILLEGAL csrr t0, CSR_AMEUDSZ
    li      a0, 0
    j       semihost_exit

trap_handler:
    csrr    t0, mcause
    li      t1, 2
    bne     t0, t1, fail
    li      t0, 1
    bne     s0, t0, fail
    li      s0, 2
    csrw    mepc, s1
    mret

fail:
    li      a0, 1

semihost_exit:
    lla     a1, semiargs
    li      t0, 0x20026
#if __riscv_xlen == 64
    sd      t0, 0(a1)
    sd      a0, 8(a1)
#else
    sw      t0, 0(a1)
    sw      a0, 4(a1)
#endif
    li      a0, 0x20
    .balign 16
    slli    zero, zero, 0x1f
    ebreak
    srai    zero, zero, 0x7
    j       .

    .bss
    .balign 16
semiargs:
#if __riscv_xlen == 64
    .space  16
#else
    .space  8
#endif
